"""Check local Markdown links, config examples, schema and installed CLI reference."""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

from ohobs_pipeline.cli import parser
from ohobs_pipeline.config import Config, load_config

ROOT = Path(__file__).resolve().parents[1]


def command_paths(command, prefix=()):
    yield prefix
    for action in command._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, child in action.choices.items():
                yield from command_paths(child, (*prefix, name))


def generated():
    sections = [
        (
            "# Installed CLI help\n\nGenerated by `python scripts/check_docs.py --write`. "
            "Run each command with --help for its complete syntax.\n"
        )
    ]
    for path in command_paths(parser()):
        result = subprocess.run(
            [sys.executable, "-m", "ohobs_pipeline", *path, "--help"],
            check=True,
            capture_output=True,
            text=True,
        )
        command = " ".join(("osp", *path))
        sections.append(f"\n## {command}\n\n```text\n{result.stdout.rstrip()}\n```\n")
    return {
        ROOT / "docs/api/configuration-schema.json": json.dumps(
            Config.model_json_schema(), indent=2, ensure_ascii=False
        )
        + "\n",
        ROOT / "docs/api/cli-help.md": "".join(sections),
    }


def main():
    options = argparse.ArgumentParser(description=__doc__)
    options.add_argument("--write", action="store_true")
    args = options.parse_args()
    for path, content in generated().items():
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        else:
            saved = path.read_text(encoding="utf-8")
            if path.suffix == ".json":
                matches = json.loads(saved) == json.loads(content)
            else:
                # argparse wraps and phrases help differently across Python releases.
                # Compare command sections and available options rather than typography.
                def interface(text):
                    return {
                        section.splitlines()[0]: set(re.findall(r"--[a-z][a-z-]*", section))
                        for section in text.split("\n## ")[1:]
                    }

                matches = interface(saved) == interface(content)
            if not matches:
                raise ValueError(f"stale generated documentation: {path.relative_to(ROOT)}")
    for config in (ROOT / "configs").rglob("*.yaml"):
        load_config(config)
    files = [*ROOT.glob("*.md"), *(ROOT / "docs").rglob("*.md")]
    failures = []
    for file in files:
        prose = re.sub(r"```.*?```", "", file.read_text(encoding="utf-8"), flags=re.DOTALL)
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", prose):
            target = unquote(target.split("#", 1)[0])
            if not target or re.match(r"[a-zA-Z]+:", target):
                continue
            if not (file.parent / target).exists():
                failures.append(f"{file.relative_to(ROOT)}: {target}")
    if failures:
        raise ValueError("broken local links:\n" + "\n".join(failures))
    print(f"Validated {len(files)} Markdown files, config examples, schema and CLI help")


if __name__ == "__main__":
    main()
